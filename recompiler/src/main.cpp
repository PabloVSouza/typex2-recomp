// x2recomp: statically recompile a Type X2 game executable into C.
//
// usage: x2recomp <game.exe> <out_dir> [--entry 0xADDR]...
//
// Output (all in out_dir):
//   funcs.h         prototypes for every recompiled function
//   funcs_NNN.c     function bodies, chunked for parallel compilation
//   table.c         guest address -> host function table, import table, image info
//   sources.cmake   list of generated sources for the runtime build
//   report.txt      discovery and lifting statistics, unsupported instructions
#include <chrono>
#include <cstdlib>
#include <cstring>
#include <cstdio>
#include <filesystem>
#include <format>
#include <fstream>
#include <map>
#include <set>
#include <vector>

#include "discover.hpp"
#include "lift.hpp"

namespace fs = std::filesystem;
using std::format;

int main(int argc, char** argv) {
    if (argc < 3) {
        std::fprintf(stderr, "usage: x2recomp <game.exe> <out_dir> [--entry 0xADDR]...\n");
        return 1;
    }
    std::vector<uint32_t> extra;
    for (int i = 3; i + 1 < argc; i += 2)
        if (std::string(argv[i]) == "--entry") extra.push_back((uint32_t)std::stoul(argv[i + 1], nullptr, 0));

    auto t0 = std::chrono::steady_clock::now();
    x2::Image img;
    try {
        img = x2::load_pe(argv[1]);
    } catch (const std::exception& e) {
        std::fprintf(stderr, "x2recomp: %s\n", e.what());
        return 1;
    }
    x2::Discovery disc(img);
    disc.run(extra);
    auto cov = disc.covered();
    size_t text = 0;
    for (auto& s : img.sections)
        if (s.exec) text += s.end - s.start;
    size_t ninsn = 0;
    {
        std::set<uint32_t> seen;
        for (auto& [e, fn] : disc.funcs)
            for (auto& [s, b] : fn.blocks)
                for (auto* i : b.insns) seen.insert(i->addr);
        ninsn = seen.size();
    }
    std::fprintf(stderr, "discovered %zu functions, %zu instructions, %.1f%% of .text\n", disc.funcs.size(), ninsn,
                 100.0 * cov.size() / text);

    fs::path out = argv[2];
    x2::Lifter lifter(img, disc);

    // --emit-tests: out is a .c file of single-instruction tests for tools/lifttest
    if (std::string(argv[2]).ends_with(".c")) {
        int per = 24;
        uint32_t range_lo = 0, range_hi = 0;  // X2_TEST_RANGE=lo-hi: every instruction in range
        if (const char* r = getenv("X2_TEST_RANGE")) {
            range_lo = (uint32_t)strtoul(r, nullptr, 16);
            if (const char* dash = strchr(r, '-')) range_hi = (uint32_t)strtoul(dash + 1, nullptr, 16);
        }
        std::map<std::string, int> taken;
        std::set<std::string> seen_bytes;
        std::set<uint32_t> addrs;
        for (auto& [e, fn] : disc.funcs)
            for (auto& [s, b] : fn.blocks)
                for (auto* i : b.insns) addrs.insert(i->addr);
        std::ofstream t(out);
        t << "/* generated by x2recomp: single-instruction lifter tests */\n#include \"x2/recomp.h\"\n\n";
        std::string table;
        int n = 0;
        for (uint32_t a : addrs) {
            if (!img.is_code(a) || img.avail(a) < 16) continue;
            const auto& ins = disc.decode(a);
            std::string bytes((const char*)img.ptr(a), ins.size);
            bool in_range = range_hi && a >= range_lo && a < range_hi;
            if (range_hi && !in_range) continue;
            if (!in_range && seen_bytes.count(bytes)) continue;
            std::vector<std::string> lines;
            std::string text;
            if (!lifter.lift_single(a, lines, text)) continue;
            std::string mn = text.substr(0, text.find(' '));
            if (text.find("fs:") != std::string::npos || text.find("gs:") != std::string::npos) continue;
            if (!in_range && taken[mn] >= per) continue;
            taken[mn]++;
            seen_bytes.insert(bytes);
            t << format("static void t_{}(X2Cpu *c) {{ LOCALS(); SET_EFLAGS(c->eflags);\n", n);
            for (auto& l : lines) t << "  " << l << "\n";
            t << "  c->eflags = GET_EFLAGS(); SPILL(); }\n";
            std::string esc;
            for (char ch : text) esc += ch == '"' ? '\'' : ch;
            table += format("  {{0x{:x}u, {}, \"{}\", t_{}}},\n", a, ins.size, esc, n);
            n++;
        }
        t << "\ntypedef struct { u32 addr; u32 len; const char *text; void (*fn)(X2Cpu *); } X2Test;\n";
        t << "const X2Test x2_tests[] = {\n" << table << "};\n";
        t << format("const unsigned x2_test_count = {};\n", n);
        std::fprintf(stderr, "emitted %d instruction tests (%zu mnemonics) to %s\n", n, taken.size(), argv[2]);
        return 0;
    }
    fs::create_directories(out);

    {
        std::ofstream h(out / "funcs.h");
        h << "/* generated by x2recomp - do not edit */\n#pragma once\n#include \"x2/recomp.h\"\n\n";
        for (auto& [e, fn] : disc.funcs) h << format("void f_{:08x}(X2Cpu *c);\n", e);
    }

    std::vector<std::string> sources;
    const size_t kChunkBytes = 3u << 20;
    std::ofstream chunk;
    size_t chunk_bytes = kChunkBytes;
    for (auto& [e, fn] : disc.funcs) {
        if (chunk_bytes >= kChunkBytes) {
            if (chunk.is_open()) chunk.close();
            std::string name = format("funcs_{:03}.c", sources.size());
            sources.push_back(name);
            chunk.open(out / name);
            chunk << "/* generated by x2recomp - do not edit */\n#include \"funcs.h\"\n\n";
            chunk_bytes = 0;
        }
        std::string code = lifter.lift_function(fn);
        chunk << code << "\n";
        chunk_bytes += code.size();
    }
    chunk.close();

    {
        std::ofstream t(out / "table.c");
        t << "/* generated by x2recomp - do not edit */\n#include \"funcs.h\"\n\n";
        t << "const X2FuncEntry x2_func_table[] = {\n";
        for (auto& [e, fn] : disc.funcs) t << format("  {{0x{:08x}u, f_{:08x}}},\n", e, e);
        t << "};\n";
        t << format("const unsigned x2_func_count = {};\n\n", disc.funcs.size());
        t << "const X2ImportEntry x2_import_table[] = {\n";
        for (auto& [slot, imp] : img.imports) t << format("  {{0x{:08x}u, \"{}\", \"{}\"}},\n", slot, imp.dll, imp.name);
        t << "};\n";
        t << format("const unsigned x2_import_count = {};\n\n", img.imports.size());
        uint32_t text_start = 0, text_end = 0;
        for (auto& s : img.sections)
            if (s.exec && !text_start) text_start = s.start, text_end = s.end;
        t << format("const X2ImageInfo x2_image = {{0x{:x}u, 0x{:x}u, 0x{:x}u, 0x{:x}u, 0x{:x}u}};\n", img.base, img.size,
                    img.entry, text_start, text_end);
        t << "const uint32_t x2_tls_callbacks[] = {";
        for (uint32_t cb : img.tls_callbacks) t << format("0x{:x}u, ", cb);
        t << "0};\n";
    }
    sources.push_back("table.c");
    {
        std::ofstream s(out / "sources.cmake");
        s << "set(X2_GEN_SOURCES\n";
        for (auto& n : sources) s << "  ${X2_GEN_DIR}/" << n << "\n";
        s << ")\n";
    }

    std::vector<std::pair<int, std::string>> uns;
    int total_uns = 0;
    for (auto& [k, v] : lifter.unsupported) uns.push_back({v, k}), total_uns += v;
    std::sort(uns.rbegin(), uns.rend());
    {
        std::ofstream r(out / "report.txt");
        r << format("functions {}\ninstructions {}\ntext coverage {:.2f}%\nunsupported {}\n\n", disc.funcs.size(), ninsn,
                    100.0 * cov.size() / text, total_uns);
        for (auto& [n, k] : uns) r << format("{:6} {}\n", n, k);
    }
    double secs = std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count();
    std::fprintf(stderr, "lifted into %zu sources in %.1fs; %d unsupported instruction sites (see report.txt)\n",
                 sources.size(), secs, total_uns);
    return 0;
}
